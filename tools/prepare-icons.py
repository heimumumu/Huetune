"""Pack the generated monochrome artwork as small LVGL alpha masks."""
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "firmware/assets"


def mask(name, size):
    with Image.open(ASSETS / f"{name}.png") as image:
        alpha = image.getchannel("A")
        bounds = alpha.point(lambda value: 255 if value >= 128 else 0).getbbox()
        if bounds is None:
            raise ValueError(f"{name} has no opaque artwork")
        glyph = alpha.crop(bounds)
        glyph.thumbnail((size - 2, size - 2), Image.Resampling.LANCZOS)
        canvas = Image.new("L", (size, size))
        canvas.paste(glyph, ((size - glyph.width) // 2, (size - glyph.height) // 2))
        return canvas


def main():
    chevron = mask("chevron", 14)
    arrow = mask("arrow", 14)
    glyphs = {
        "play": mask("play", 14),
        "pause": mask("pause", 14),
        "help": mask("help", 20),
        "chevron_left": chevron,
        "chevron_right": ImageOps.mirror(chevron),
        "arrow_up": arrow,
        "arrow_down": arrow.transpose(Image.Transpose.ROTATE_180),
        "arrow_left": arrow.transpose(Image.Transpose.ROTATE_90),
        "arrow_right": arrow.transpose(Image.Transpose.ROTATE_270),
    }
    lines = [
        "// Generated by tools/prepare-icons.py from firmware/assets.",
        "#pragma once",
        '#include "lvgl.h"',
        "",
        "namespace icons {",
        "template <uint16_t Size>",
        "constexpr lv_image_dsc_t descriptor(const uint8_t (&pixels)[Size*Size]){",
        "    lv_image_dsc_t result{};",
        "    result.header.magic=LV_IMAGE_HEADER_MAGIC;",
        "    result.header.cf=LV_COLOR_FORMAT_A8;",
        "    result.header.w=result.header.h=result.header.stride=Size;",
        "    result.data_size=sizeof(pixels);",
        "    result.data=pixels;",
        "    return result;",
        "}",
    ]
    for name, glyph in glyphs.items():
        pixels = glyph.tobytes()
        size = glyph.width
        lines.append(f"inline constexpr uint8_t {name}_pixels[]={{")
        for offset in range(0, len(pixels), size):
            lines.append("    " + ",".join(str(value) for value in pixels[offset:offset + size]) + ",")
        lines.append("};")
        lines.append(f"inline constexpr auto {name}=descriptor<{size}>({name}_pixels);")
    lines.extend(["}", ""])
    (ROOT / "firmware/main/ui_icons.hpp").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
